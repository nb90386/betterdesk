// Drives /demo end to end and screenshots every step: node scripts/demo-flow.mjs <baseUrl> <outDir> [width]
import path from "node:path";
import fs from "node:fs";
import { chromium } from "@playwright/test";
process.env.PLAYWRIGHT_BROWSERS_PATH ??= path.resolve(".pw-browsers");
const [base, out, w = "1440"] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const exe = `${process.env.HOME}/Library/Caches/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-mac-arm64/chrome-headless-shell`;
const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? exe });
const p = await b.newPage({ viewport: { width: Number(w), height: 1000 } });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => m.type() === "error" && errs.push(m.text().slice(0, 300)));
await p.goto(base + "/demo", { waitUntil: "networkidle" });
const shot = async (n) => { await p.waitForTimeout(700); await p.screenshot({ path: `${out}/demo-${w}-${n}.png`, fullPage: true }); };
const click = async (name) => { await p.getByRole("button", { name }).first().click(); };
await shot("1-presence");
await click("Make it a task");
await click("Import the list and run Scout");
await shot("2-scout-running");
await p.getByRole("button", { name: "Next: review the introduction" }).waitFor({ timeout: 15000 });
await shot("2-scout-done");
await click("Next: review the introduction");
await shot("3-draft");
await click(/^Approve$/);
await click("Simulate delivery");
await shot("4-thread");
await click("Play the sample reply");
await shot("5-reply");
await p.locator("main button", { hasText: /AM|PM/ }).first().click();
await p.getByRole("link", { name: "Open the record in the workspace" }).waitFor();
await shot("6-record");
await p.getByRole("link", { name: "Open the record in the workspace" }).click();
await p.waitForLoadState("networkidle");
await shot("7-app-record");
console.log(errs.length ? "ERRORS:\n" + errs.join("\n") : "flow complete, no console errors");
await b.close();
