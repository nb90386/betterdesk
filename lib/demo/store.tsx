"use client";

/**
 * DEMO workspace store. Runs the same pure workspace actions a backend would, against a
 * browser-local copy of the fictional sample workspace. Persistence: localStorage in this
 * browser only (survives refresh and navigation; "Reset sample" restores the baseline).
 * Nothing here can send email, text, call or touch a real calendar.
 */
import { createContext, useCallback, useContext, useEffect, useMemo, useRef, useState, useSyncExternalStore } from "react";
import type { Workspace } from "@/lib/domain/types";
import type { Actor } from "@/lib/workspace/model";
import { createSampleWorkspace } from "@/lib/demo/seed";
import { ActionError, stepRun } from "@/lib/workspace/actions";
import { isActive } from "@/lib/domain/run";

const KEY = "betterdesk.v5.demo-workspace";
export const CURRENT_USER: Actor = { kind: "user", id: "usr_dana", name: "Dana Ortiz" };
/** Visible pacing between Scout tasks so each step can be inspected or canceled. No content is generated by the delay. */
export const STEP_PACING_MS = 700;

type Result = { ok: true } | { ok: false; error: string };
type Ctx = {
  ws: Workspace;
  ready: boolean;
  act: (fn: (ws: Workspace, at: string, me: Actor) => Workspace, announce?: string) => Result;
  reset: () => void;
  announcement: string;
};

const StoreCtx = createContext<Ctx | null>(null);

function load(): Workspace | null {
  try {
    const raw = window.localStorage.getItem(KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw) as Workspace;
    return parsed && parsed.version === 2 && parsed.org?.mode === "DEMO" ? parsed : null;
  } catch {
    return null;
  }
}

const noop = () => () => {};

export function DemoWorkspaceProvider({ children }: { children: React.ReactNode }) {
  const hydrated = useSyncExternalStore(noop, () => true, () => false);
  const [ws, setWs] = useState<Workspace>(() => (typeof window === "undefined" ? createSampleWorkspace() : load() ?? createSampleWorkspace()));
  const [announcement, setAnnouncement] = useState("");
  const wsRef = useRef(ws);

  useEffect(() => {
    wsRef.current = ws;
    try {
      window.localStorage.setItem(KEY, JSON.stringify(ws));
    } catch {
      /* storage unavailable (private mode): the sandbox still works for this tab */
    }
  }, [ws]);

  const act = useCallback<Ctx["act"]>((fn, announce) => {
    try {
      const next = fn(wsRef.current, new Date().toISOString(), CURRENT_USER);
      wsRef.current = next;
      setWs(next);
      if (announce) setAnnouncement(announce);
      return { ok: true };
    } catch (e) {
      const error = e instanceof ActionError || e instanceof Error ? e.message : "Something went wrong.";
      setAnnouncement(error);
      return { ok: false, error };
    }
  }, []);

  const reset = useCallback(() => {
    const fresh = createSampleWorkspace();
    wsRef.current = fresh;
    setWs(fresh);
    setAnnouncement("Sample workspace reset.");
  }, []);

  // Drive active Scout runs one task at a time.
  const active = ws.runs.find((r) => isActive(r.state));
  useEffect(() => {
    if (!active) return;
    const t = window.setTimeout(() => {
      const next = stepRun(wsRef.current, active.id, new Date().toISOString());
      wsRef.current = next;
      setWs(next);
      const run = next.runs.find((r) => r.id === active.id);
      if (run && !isActive(run.state)) setAnnouncement(`Scout run ${run.state.replace("-", " ")}.`);
    }, STEP_PACING_MS);
    return () => window.clearTimeout(t);
  }, [active]);

  const value = useMemo(() => ({ ws, ready: hydrated, act, reset, announcement }), [ws, hydrated, act, reset, announcement]);
  return (
    <StoreCtx.Provider value={value}>
      {children}
      <p className="sr-only" aria-live="polite" role="status">{announcement}</p>
    </StoreCtx.Provider>
  );
}

export function useWorkspace() {
  const c = useContext(StoreCtx);
  if (!c) throw new Error("useWorkspace must be used inside DemoWorkspaceProvider");
  return c;
}
